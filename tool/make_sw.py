"""Write build/web/sw.js: a service worker that caches the whole app so it opens with no internet.

Run after `flutter build web`. Renderer variants Safari does not load (skwasm, wimp, chromium canvaskit, symbols) are not precached;
anything else fetched later is cached on first use.
"""
import hashlib, json, pathlib

web = pathlib.Path(__file__).resolve().parent.parent / "build" / "web"
skip = {"sw.js", "flutter_service_worker.js", "version.json"}
files, h = [], hashlib.sha256()
for p in sorted(web.rglob("*")):
    rel = p.relative_to(web).as_posix()
    if (p.is_dir() or rel in skip or rel.startswith("canvaskit/chromium/") or "skwasm" in rel or rel.endswith((".map", ".symbols"))
            or rel.startswith(("canvaskit/wimp", "canvaskit/webparagraph/"))):
        continue
    files.append(rel)
    h.update(rel.encode()); h.update(p.read_bytes())
version = h.hexdigest()[:12]

sw = f"""// Generated by tool/make_sw.py. Version changes whenever any app file changes.
// Each app folder (the current app, v2/) has its own worker; caches are named per folder so
// one never deletes the other's.
const SCOPE = new URL(self.registration.scope).pathname;
const PREFIX = 'app:' + SCOPE + ':';
const CACHE = PREFIX + '{version}';
const FILES = {json.dumps(['./'] + files)};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, {{ cache: 'reload' }})))).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => (k.startsWith(PREFIX) && k !== CACHE) ||
      // Caches from before per-folder names belonged to the app at the top folder.
      (k.startsWith('warehouse-') && SCOPE.split('/').filter(Boolean).length <= 1)).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

// Page loads: try the network first so updates arrive, fall back to the cache when offline.
// Both the page and the install step skip the browser's HTTP cache, so a new version never
// gets saved with files from the old one.
// Everything else: cache first.
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {{
    // Only this app's own page: another version published in a sub-folder (e.g. v2/) has its own worker.
    const path = new URL(req.url).pathname, scope = new URL(self.registration.scope).pathname;
    if (path !== scope && path !== scope + 'index.html') return;
    e.respondWith(fetch(req.url, {{ cache: 'no-cache' }}).then((res) => {{
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put('./', copy));
      return res;
    }}).catch(() => caches.match('./')));
    return;
  }}
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).then((res) => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }}
    return res;
  }})));
}});
"""
(web / "sw.js").write_text(sw)
size = sum((web / f).stat().st_size for f in files)
print(f"sw.js: {len(files)} files, {size / 1e6:.1f} MB precached, version {version}")
